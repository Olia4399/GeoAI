CREATE TABLE IF NOT EXISTS population_grid (
    id SERIAL PRIMARY KEY,
    grid_id VARCHAR(64),
    pop_density FLOAT NOT NULL,   -- 人/km²（示意或真实）
    score FLOAT,                  -- 0-100 归一化，便于适宜性叠加
    district VARCHAR(100),
    geom GEOMETRY(POLYGON, 4326) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_population_grid_geom ON population_grid USING GIST(geom);
CREATE INDEX IF NOT EXISTS idx_population_grid_district ON population_grid (district);
